"""dataset.npz -> docs/MOTION_STATS.json (+ .md): the real-people reference, per state, robust across people.
Usage: python -I reference_stats.py <scratch> <docs_dir> [--split val]   (split: all | train | val)"""
import json, sys, os
from pathlib import Path
import numpy as np
sys.path.insert(0, os.path.dirname(__file__))
import mstats


def load_people(root, split="all"):
    D = dict(np.load(Path(root) / "dataset.npz"))
    meta = json.loads((Path(root) / "dataset_meta.json").read_text())
    val = set(json.loads((Path(root) / "split.json").read_text())["val"]) if split != "all" and (Path(root) / "split.json").exists() else set()
    groups = {}
    for i, (a, b) in enumerate(D["seg"]):
        v = int(D["segvid"][i]); p = int(D["segperson"][i])
        vid = meta[v]["id"]
        if split == "val" and vid not in val: continue
        if split == "train" and vid in val: continue
        selfsp = D["sv"][a:b, 3] > 0
        seg = dict(M=D["M"][a:b], blink=D["blink"][a:b], blinkdur=D["blinkdur"][a:b], st=D["st"][a:b].astype(int),
                   selfsp=selfsp, partsp=D["pv"][a:b, 3] > 0, f0=D["sraw"][a:b, 1] * selfsp,
                   pM=D["pM"][a:b] if np.isfinite(D["pM"][a:b, 12]).any() else None)
        groups.setdefault((v, p), []).append(seg)
    return groups, meta


def md_table(ref, keys):
    rows = ["| metric | speaking | listening | idle |", "|---|---|---|---|"]
    for k in keys:
        cells = []
        for s in ("speaking", "listening", "idle"):
            x = ref.get(s, {}).get(k)
            cells.append("—" if x is None else f"{x['med']:.3g} [{x['q25']:.3g}, {x['q75']:.3g}] (n={x['n']})")
        rows.append(f"| {k} | " + " | ".join(cells) + " |")
    return "\n".join(rows)


def main():
    root, docs = sys.argv[1], Path(sys.argv[2])
    split = sys.argv[sys.argv.index("--split") + 1] if "--split" in sys.argv else "all"
    groups, meta = load_people(root, split)
    people = []
    for (v, p), segs in groups.items():
        ps = mstats.person_stats(segs)
        ps["_id"] = f"{meta[v]['id']}#{p}"; ps["_cat"] = meta[v]["category"]
        people.append(ps)
    ref = mstats.aggregate(people)
    mins = {s: sum(p.get(s, {}).get("minutes", 0) for p in people) for s in ("speaking", "listening", "idle")}
    ref["_meta"] = dict(people=len(people), videos=len({k[0] for k in groups}), minutes_by_state=mins, split=split,
                        note="per-person values; med/q25/q75 across people. Units: deg, deg/s, cm, per-minute, ms, "
                             "log10 deg^2/Hz for psd, shoulder-widths/s for arm. Head angles relative to each "
                             "person's median pose, 6 Hz zero-phase low-passed (tracker noise).")
    docs.mkdir(parents=True, exist_ok=True)
    name = "MOTION_STATS" if split == "all" else f"MOTION_STATS_{split}"
    (docs / f"{name}.json").write_text(json.dumps(ref, indent=1))
    keys = ["minutes", "head_yaw_sd10s", "head_pitch_sd10s", "head_roll_sd10s", "head_yaw_speed_med", "head_pitch_speed_med",
            "head_roll_speed_med", "head_yaw_speed_p90", "head_pitch_speed_p90", "head_pitch_psd_0.1_0.5Hz",
            "head_pitch_psd_1.0_2.0Hz", "head_pitch_psd_4.0_8.0Hz", "head_tx_sd10s_cm", "head_ty_sd10s_cm", "head_tz_sd10s_cm",
            "stillness_frac", "nod_per_min", "bignod_per_min", "blink_per_min", "blink_dur_ms_med", "gshift_per_min", "avert_frac",
            "avert_per_min", "avert_dur_s_med", "smile_mean", "smile_sd", "smile_per_min", "brow_sd", "brow_per_min",
            "arm_speed_med", "arm_speed_p90", "gesture_frac"]
    cp = ref["coupling"]
    cpl = "\n".join(f"| {k} | {v['med']:.3g} [{v['q25']:.3g}, {v['q75']:.3g}] (n={v['n']}) |" for k, v in cp.items() if isinstance(v, dict) and "med" in v)
    extra = ""
    if "nod_offset_hist" in cp:
        h = cp["nod_offset_hist"]; extra += f"\nNod offsets from partner-pause onsets (listening), n={h['n']}, median {h['median_s']:.2f} s:\n\n" + \
            "| bin (s) | " + " | ".join(f"{a:+.2f}" for a in h["edges_s"][:-1]) + " |\n|---|" + "---|" * len(h["counts"]) + \
            "\n| count | " + " | ".join(str(c) for c in h["counts"]) + " |\n"
    if "smile_xcorr_mean_curve" in cp:
        c = cp["smile_xcorr_mean_curve"]; extra += f"\nSmile mirroring (dyads, n={c['n']} people): mean cross-correlation peak r={c['peak_r']:.3f} at lag {c['peak_lag_s']:+.2f} s (+ = this person follows the partner).\n"
    md = f"""# Real-people motion statistics ({split})

Generated by `tools/prior/reference_stats.py` from the corpus in `docs/CORPUS.md`. {len(people)} people in
{ref['_meta']['videos']} videos; minutes by state: speaking {mins['speaking']:.0f}, listening {mins['listening']:.0f},
idle {mins['idle']:.0f}. Cells: median across people [25th, 75th percentile] (n people with enough time in that
state). Head angles in degrees relative to the person's own median pose; speeds deg/s; translation cm; psd
log10(deg²/Hz) of the head angle in that band; rates per minute; arm = wrist speed in shoulder widths/s.
States: speaking = own turn (gaps < 1.2 s bridged); listening = someone else speaking; idle = nobody.

{md_table(ref, keys)}

## Couplings (per person, median across people)

| coupling | value |
|---|---|
{cpl}

Lift = P(event in the window around the cue) / P(event in a random window of the same length); 1 = no coupling.
Windows: blink 0..0.5 s after own speech onset; blink ±0.2 s of a gaze shift; brow raise ±0.3 s of a pitch accent;
nod −0.2..+0.3 s of an accent; nod −0.5..+1.0 s of a partner pause onset.
{extra}
"""
    (docs / f"{name}.md").write_text(md)
    print(md[:4000])


if __name__ == "__main__":
    main()
