#!/usr/bin/env node
// tools/think_geom.cjs [--write | --check] — each character's own face / arm geometry for the thinking
// gesture's chin target (app/motion.js makeShapeChin). Read from each shape's shader (renderer/animals/<c>.glsl: the
// mouth frame LIP_O / LIP_W / LIP_HL of engine/lips.glsl, the arm SA_SHO / SA_REST / SA_LEN / SA_R / SA_HAND of
// engine/shape_arms.glsl, SHAPE_PIVOT / SHAPE_YAW0 of engine/face.glsl) and written into the generated block of
// app/motion.js between "// <think-geom>" and "// </think-geom>". A shape = any character whose shader includes
// shape_arms. --check (tests/think_test.cjs runs it): exit 1 when the block is stale; --write: rewrite it; none: print.
'use strict';
const fs = require('fs'), path = require('path');
const ROOT = path.resolve(__dirname, '..'), ANIM = path.join(ROOT, 'renderer', 'animals'), MOTION = path.join(ROOT, 'app', 'motion.js');
const DEFAULTS = {SHAPE_YAW0: '0.0', LIP_HL: '(0.098*LIPU)', LIPU: '(LIP_W/0.27)'};   // engine/face.glsl, engine/lips.glsl
function defines(src) {
  const d = {};
  for (const m of src.matchAll(/^#define\s+(\w+)\s+(.+?)\s*(?:\/\/.*)?$/gm)) if (!(m[1] in d)) d[m[1]] = m[2].trim();
  return d;
}
function evalExpr(name, d, depth = 0) {
  let e = d[name] !== undefined ? d[name] : DEFAULTS[name];
  if (e === undefined || depth > 8) throw new Error('no define ' + name);
  const v3 = /^vec3\(([^()]+)\)$/.exec(e);
  const num = s => {
    const js = s.replace(/[A-Za-z_]\w*/g, id => { const r = evalExpr(id, d, depth + 1); if (typeof r !== 'number') throw new Error(id + ' is not a number'); return '(' + r + ')'; });
    if (!/^[-+*/().\d\seE]+$/.test(js)) throw new Error('cannot evaluate ' + name + ' = ' + s);
    return Function('"use strict"; return (' + js + ');')();
  };
  return v3 ? v3[1].split(',').map(num) : num(e);
}
// An animal whose shader maps the hand columns LINEARLY around its rest wrist and has no chin pose of its own (the
// monkey): wrist (torso frame, mirrored) = WRIST0 + L*(hx, hy, zk*hz) + (0, 0, zup*smoothstep(0, 1, hy)), the torso turned
// BYAW against the world, the head YAW0 about NECK, the muzzle an ellipsoid the wrist is pushed out of. The exact
// lines are matched: a shader that changes its mapping drops out of the table (and --check says the block is stale).
function linearArm(src) {
  const c = (name, vec) => { const m = new RegExp('^const\\s+' + (vec ? 'vec3' : 'float') + '\\s+(?:\\w+\\s*=\\s*[^,;]+,\\s*)*?' + name + '\\s*=\\s*' + (vec ? 'vec3\\(([^)]+)\\)' : '([-\\d.]+)'), 'm').exec(src); return m ? (vec ? m[1].split(',').map(Number) : +m[1]) : null; };
  const L = /const float L = ([\d.]+)\*\(BONE_U \+ BONE_F\);/.exec(src), T = /vec3 T = WRIST0 \+ L\*vec3\(hx, hy, ([\d.]+)\*hz\);/.exec(src);
  const up = /T\.z \+= ([\d.]+)\*smoothstep\(0\.0, 1\.0, hy\);/.exec(src);
  const mz = /Th = pushOut\(Th, vec3\(([^)]+)\), vec3\(([^)]+)\), [\d.]+\);\s*\/\/ the muzzle/.exec(src);
  const w0 = c('WRIST0', 1), neck = c('NECK', 1), bu = c('BONE_U'), bf = c('BONE_F'), byaw = c('BYAW'), yaw0 = c('YAW0');
  if (!L || !T || !up || !mz || !w0 || !neck || bu == null || bf == null || byaw == null || yaw0 == null) return null;
  const r = v => Array.isArray(v) ? v.map(x => +x.toFixed(4)) : +v.toFixed(4);
  return {kind: 'arm', wrist0: r(w0), len: r(+L[1] * (bu + bf)), zk: +T[1], zup: +up[1], neck: r(neck), byaw: r(byaw), yaw0: r(yaw0),
    muzC: r(mz[1].split(',').map(Number)), muzR: r(mz[2].split(',').map(Number))};
}
function geom() {
  const out = {};
  for (const f of fs.readdirSync(ANIM).filter(f => f.endsWith('.glsl')).sort()) {
    const src = fs.readFileSync(path.join(ANIM, f), 'utf8');
    if (!/^#pragma include shape_arms/m.test(src)) { const a = linearArm(src); if (a) out[f.replace(/\.glsl$/, '')] = a; continue; }
    const d = defines(src), r = v => Array.isArray(v) ? v.map(x => +x.toFixed(4)) : +v.toFixed(4);
    out[f.replace(/\.glsl$/, '')] = {kind: 'shape', lip: r(evalExpr('LIP_O', d)), lipW: r(evalExpr('LIP_W', d)), lipHL: r(evalExpr('LIP_HL', d)),
      sho: r(evalExpr('SA_SHO', d)), rest: r(evalExpr('SA_REST', d)), len: r(evalExpr('SA_LEN', d)), armR: r(evalExpr('SA_R', d)), hand: r(evalExpr('SA_HAND', d)),
      pivot: r(evalExpr('SHAPE_PIVOT', d)), yaw0: r(evalExpr('SHAPE_YAW0', d))};
  }
  return out;
}
function block(G) {
  return '    // <think-geom> generated by tools/think_geom.cjs --write from renderer/animals/*.glsl — do not edit by hand\n    const CHIN_GEOM = {\n'
    + Object.entries(G).map(([c, g]) => `      ${c}: ${JSON.stringify(g).replace(/"(\w+)":/g, '$1: ').replace(/,/g, ', ')},`).join('\n') + '\n    };\n    // </think-geom>';
}
if (require.main === module) {
  const G = geom(), want = block(G), src = fs.readFileSync(MOTION, 'utf8');
  const re = /    \/\/ <think-geom>[\s\S]*?\/\/ <\/think-geom>/, cur = (re.exec(src) || [''])[0];
  if (process.argv.includes('--write')) {
    if (!cur) { console.error('no <think-geom> block in app/motion.js'); process.exit(2); }
    if (cur !== want) fs.writeFileSync(MOTION, src.replace(re, () => want));
    console.log(cur === want ? 'up to date' : 'written', Object.keys(G).join(' '));
  } else if (process.argv.includes('--check')) {
    if (cur !== want) { console.error('app/motion.js <think-geom> block is stale: run node tools/think_geom.cjs --write'); process.exit(1); }
    console.log('ok', Object.keys(G).join(' '));
  } else console.log(want);
}
module.exports = {geom, block};
